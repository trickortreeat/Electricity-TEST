import type { DeviceDef, DeviceType, LevelDef, TerminalDef } from './types';

// Хелпер создания устройства: terminals = [key, dx, dy, net, label?]
function dev(
  id: string,
  type: DeviceType,
  x: number,
  y: number,
  label: string | undefined,
  terms: Array<[string, number, number, string | null, string?]>,
  sublabel?: string,
): DeviceDef {
  return {
    id,
    type,
    x,
    y,
    label,
    sublabel,
    terminals: terms.map(
      ([key, dx, dy, net, tlabel]): TerminalDef => ({ key, dx, dy, net, label: tlabel }),
    ),
  };
}

export const tid = (deviceId: string, key: string) => `${deviceId}:${key}`;

