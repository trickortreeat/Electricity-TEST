export const QUESTION_BANK: BankQuestion[] = Q.slice(0, 300);
export const TOPICS = Array.from(new Set(QUESTION_BANK.map((q) => q.topic)));

export function pickQuestions(count: number, topic?: string): BankQuestion[] {
  const pool = topic && topic !== 'Все темы' ? QUESTION_BANK.filter((q) => q.topic === topic) : [...QUESTION_BANK];
  const out: BankQuestion[] = [];
  const used = new Set<string>();
  while (out.length < Math.min(count, pool.length)) {
    const q = pool[Math.floor(Math.random() * pool.length)];
    if (used.has(q.id)) continue;
    used.add(q.id);
    // перемешиваем варианты, сохраняя правильный
    const right = q.options[q.correct];
    const shuffled = [...q.options].sort(() => Math.random() - 0.5);
    out.push({ ...q, options: shuffled, correct: shuffled.indexOf(right) });
  }
  return out;
}
